function buildSizes(seed: number): { size: EUSize; stock: number }[] {
  return ALL_EU_SIZES.map((size, idx) => {
    // Ensure realistic mix of in stock, low stock (<=5), and 1-2 out of stock sizes per shoe
    const val = (seed * 7 + idx * 5) % 14;
    if (val === 0) return { size, stock: 0 };
    if (val <= 3) return { size, stock: val }; // Low stock 1..3
    return { size, stock: val + 4 }; // In stock 8..17
  });
}

function buildColors(
  colorNames: ShoeColorName[],
  baseImageIndex: number
): Product['colors'] {
  return colorNames.map((cName, idx) => {
    const found = ALL_COLORS.find((c) => c.name === cName) || ALL_COLORS[0];
    return {
      name: found.name,
      label: found.label,
      hex: found.hex,
      secondaryHex: found.secondaryHex,
      stock: 14 + ((idx * 7 + baseImageIndex * 3) % 22),
      imageIndex: (baseImageIndex + idx) % 5,
    };
  });
}

